CREATE TABLE q_backtest_experiment (
    Id BIGINT AUTO_INCREMENT PRIMARY KEY,
    ExperimentId VARCHAR(36) NOT NULL,
    DatasetId BIGINT NOT NULL,
    Provider VARCHAR(32) NOT NULL,
    MarketType VARCHAR(32) NOT NULL,
    DataType VARCHAR(32) NOT NULL,
    Symbol VARCHAR(64) NOT NULL,
    IntervalCode VARCHAR(16) NOT NULL,
    StrategyCode VARCHAR(128) NOT NULL,
    StrategyVersion VARCHAR(32) NOT NULL,
    ParameterGridJson JSON NOT NULL,
    CandidateCount INT NOT NULL,
    TrainingStartOpenTimeMs BIGINT NOT NULL,
    TrainingEndOpenTimeMs BIGINT NOT NULL,
    ValidationStartOpenTimeMs BIGINT NOT NULL,
    ValidationEndOpenTimeMs BIGINT NOT NULL,
    OrderAmount DECIMAL(38,18) NOT NULL,
    FeeRate DECIMAL(38,18) NOT NULL,
    ForceCloseAtEnd BOOLEAN NOT NULL,
    Status VARCHAR(32) NOT NULL,
    ErrorCode VARCHAR(128) NULL,
    ErrorMessage VARCHAR(1000) NULL,
    CreatedAt DATETIME(3) NOT NULL,
    UpdatedAt DATETIME(3) NOT NULL,
    StartedAt DATETIME(3) NULL,
    FinishedAt DATETIME(3) NULL,
    CONSTRAINT uq_q_backtest_experiment_id UNIQUE (ExperimentId),
    INDEX ix_q_backtest_experiment_status (Status, CreatedAt, Id),
    INDEX ix_q_backtest_experiment_strategy (StrategyCode, CreatedAt, Id),
    INDEX ix_q_backtest_experiment_symbol (Symbol, CreatedAt, Id)
);

CREATE TABLE q_backtest_experiment_candidate (
    Id BIGINT AUTO_INCREMENT PRIMARY KEY,
    CandidateId VARCHAR(36) NOT NULL,
    ExperimentId VARCHAR(36) NOT NULL,
    CandidateIndex INT NOT NULL,
    ParametersJson JSON NOT NULL,
    TrainingRunId VARCHAR(36) NOT NULL,
    ValidationRunId VARCHAR(36) NOT NULL,
    DispatchStatus VARCHAR(16) NOT NULL,
    ClaimToken VARCHAR(36) NULL,
    ClaimedAt DATETIME(3) NULL,
    ErrorCode VARCHAR(128) NULL,
    ErrorMessage VARCHAR(1000) NULL,
    CreatedAt DATETIME(3) NOT NULL,
    UpdatedAt DATETIME(3) NOT NULL,
    CONSTRAINT uq_q_backtest_experiment_candidate_id UNIQUE (CandidateId),
    CONSTRAINT uq_q_backtest_experiment_candidate_index UNIQUE (ExperimentId, CandidateIndex),
    CONSTRAINT uq_q_backtest_experiment_training_run UNIQUE (TrainingRunId),
    CONSTRAINT uq_q_backtest_experiment_validation_run UNIQUE (ValidationRunId),
    INDEX ix_q_backtest_experiment_candidate_page (ExperimentId, CandidateIndex),
    INDEX ix_q_backtest_experiment_candidate_dispatch (ExperimentId, DispatchStatus, CandidateIndex),
    INDEX ix_q_backtest_experiment_candidate_claim (DispatchStatus, ClaimedAt)
);
